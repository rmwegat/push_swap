#include "push_swap.h"

void	ft_error(void)
{
	ft_putstr_fd("Error\n", 2);
	ft_free_all();
	exit(1);
}

int	main(int argc, char **argv)
{
	t_stack	*a;
	t_stack	*b;

	a = NULL;
	b = NULL;
	if (argc > 1)
	{
		init_stack(&a, argc, argv);
		if (!is_sorted(a))
			sort_stack(&a, &b);
	}
	ft_free_all();
	return (0);
}